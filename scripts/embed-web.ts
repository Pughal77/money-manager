import fs from 'node:fs';
import path from 'node:path';

/**
 * Packs the output of `npx expo export -p web` (`apps/app/dist`) into
 * `apps/app/src/server/webAssets.ts` so the iPhone app can serve the compiled
 * web app directly over Wi-Fi / Personal Hotspot.
 */
const distDir = path.resolve(process.cwd(), 'apps/app/dist');
const outFile = path.resolve(process.cwd(), 'apps/app/src/server/webAssets.ts');

if (!fs.existsSync(distDir)) {
  console.error(`Error: ${distDir} does not exist. Run "npm --workspace=@mm/app run export:web" first.`);
  process.exit(1);
}

const MIME_MAP: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
};

const assets: Record<string, { contentType: string; body: string }> = {};

function walk(dir: string, prefix = '') {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = `${prefix}/${entry.name}`;
    if (entry.isDirectory()) {
      walk(full, rel);
    } else {
      const ext = path.extname(entry.name).toLowerCase();
      const contentType = MIME_MAP[ext];
      if (!contentType) continue;
      const body = fs.readFileSync(full, 'utf-8');
      assets[rel] = { contentType, body };
      if (rel === '/index.html') {
        assets['/'] = { contentType, body };
      }
    }
  }
}

walk(distDir);

const fileContent = `// AUTO-GENERATED by scripts/embed-web.ts — DO NOT EDIT MANUALLY
import type { HttpResponse } from '@mm/http-lite';

export const EMBEDDED_WEB_ASSETS: Record<string, { contentType: string; body: string }> = ${JSON.stringify(
  assets,
  null,
  2
)};

export function serveEmbeddedWebAsset(reqPath: string): HttpResponse | undefined {
  const normalized = reqPath === '' ? '/' : reqPath;
  const hit = EMBEDDED_WEB_ASSETS[normalized] ?? (!normalized.startsWith('/api/') ? EMBEDDED_WEB_ASSETS['/'] : undefined);
  if (!hit) return undefined;
  return {
    status: 200,
    headers: { 'Content-Type': hit.contentType },
    body: hit.body,
  };
}
`;

fs.writeFileSync(outFile, fileContent, 'utf-8');
console.log(`Embedded ${Object.keys(assets).length} web assets into ${outFile}`);
